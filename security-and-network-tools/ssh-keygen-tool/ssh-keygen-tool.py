def generate_keypair(
    key_type: str,
    key_path: str,
    passphrase: str = "",
    bits: Optional[int] = None,
    comment: str = "",
    email: str = ""
) -> Tuple[bool, str]:
    """
    Generate an SSH key pair using ssh-keygen.

    Args:
        key_type: Type of key (rsa, ed25519, ecdsa)
        key_path: Path where to save the key
        passphrase: Optional passphrase to encrypt the private key
        bits: Key size (not used for ed25519)
        comment: Optional comment for the key
        email: Email address (appended to comment)

    Returns:
        Tuple of (success, message)
    """
    ssh_keygen = get_available_keygen()

    if not ssh_keygen:
        return False, "ssh-keygen not found. Please install OpenSSH or Git."

    # Build comment
    if not comment:
        comment = f"{email}" if email else "Generated by SSH Key Tool"

    # Build command
    cmd = [ssh_keygen, "-t", key_type, "-f", key_path, "-C", comment]

    # Add bits for RSA and ECDSA (not needed for Ed25519)
    if key_type != "ed25519":
        key_info = KEY_TYPES.get(key_type, {})
        key_bits = bits or key_info.get("bits_default", 4096)
        cmd.extend(["-b", str(key_bits)])

    # Add passphrase if provided
    if passphrase:
        cmd.extend(["-N", passphrase])
    else:
        # Empty passphrase (not recommended for production!)
        cmd.extend(["-N", ""])

    try:
        # Run ssh-keygen
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=30
        )

        if result.returncode == 0:
            return True, f"Key pair generated successfully!"
        else:
            error_msg = result.stderr or "Unknown error"
            return False, f"Error generating key: {error_msg}"

    except subprocess.TimeoutExpired:
        return False, "Key generation timed out"
    except Exception as e:
        return False, f"Error: {e}"


def generate_keypair_python(
    key_type: str,
    key_path: str,
    passphrase: str = "",
    bits: int = 4096
) -> Tuple[bool, str]:
    """
    Generate SSH key pair using Python libraries (requires paramiko or cryptography).

    This is an alternative if ssh-keygen is not available.

    Args:
        key_type: Type of key to generate
        key_path: Path to save the key
        passphrase: Passphrase for encryption
        bits: Key size

    Returns:
        Tuple of (success, message)
    """
    try:
        # Try paramiko first
        import paramiko
        from paramiko import Ed25519Key, RSAKey, ECDSAKey

        # Generate key based on type
        if key_type == "ed25519":
            key = Ed25519Key.generate()
        elif key_type == "rsa":
            key = RSAKey.generate(bits=bits)
        elif key_type == "ecdsa":
            key = ECDSAKey.generate()
        else:
            return False, f"Unsupported key type: {key_type}"

        # Write private key
        key.write_private_key_file(key_path, password=passphrase if passphrase else None)

        # Write public key
        public_key_path = f"{key_path}.pub"
        with open(public_key_path, "w") as f:
            f.write(f"{key.get_name()} {key.asbytes().hex()}\n")

        return True, f"Key pair generated using paramiko"

    except ImportError:
        return False, "paramiko not installed. Install with: pip install paramiko"
    except Exception as e:
        return False, f"Error generating key: {e}"


def read_public_key(key_path: str) -> Optional[str]:
    """
    Read the public key from a file.

    Args:
        key_path: Path to private key file

    Returns:
        Public key string or None
    """
    public_key_path = f"{key_path}.pub"

    try:
        with open(public_key_path, "r") as f:
            return f.read().strip()
    except FileNotFoundError:
        return None
    except Exception as e:
        print(f"[!] Error reading public key: {e}")
        return None


def get_key_info(key_path: str) -> dict:
    """
    Get information about an SSH key using ssh-keygen -l.

    Args:
        key_path: Path to private key

    Returns:
        Dictionary with key information
    """
    ssh_keygen = get_available_keygen()

    if not ssh_keygen:
        return {"error": "ssh-keygen not found"}

    try:
        result = subprocess.run(
            [ssh_keygen, "-l", "-f", key_path],
            capture_output=True,
            text=True,
            timeout=10
        )

        if result.returncode == 0:
            # Parse output like: "2048 SHA256:xxxxx... comment (RSA)"
            parts = result.stdout.strip().split()
            if len(parts) >= 4:
                return {
                    "bits": parts[0],
                    "fingerprint": parts[1],
                    "comment": " ".join(parts[3:-1]),
                    "type": parts[-1].strip("()")
                }

        return {"error": result.stderr or "Could not read key info"}

    except Exception as e:
        return {"error": str(e)}


def list_ssh_keys(ssh_dir: Path = DEFAULT_KEY_DIR) -> list:
    """
    List existing SSH keys in the .ssh directory.

    Args:
        ssh_dir: Path to .ssh directory

    Returns:
        List of key file paths
    """
    if not ssh_dir.exists():
        return []

    keys = []
    for f in ssh_dir.glob("*"):
        if f.is_file() and not f.name.endswith(".pub"):
            # Check if corresponding .pub exists
            if (f.parent / f"{f.name}.pub").exists():
                keys.append(str(f))

    return keys


