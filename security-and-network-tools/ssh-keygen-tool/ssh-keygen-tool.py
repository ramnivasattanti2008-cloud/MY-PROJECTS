def main():
    """Main CLI entry point."""
    parser = argparse.ArgumentParser(
        description="Educational SSH Key Generator",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s -t ed25519 -f mykey              # Generate Ed25519 key
  %(prog)s -t rsa -b 4096 -f server_key     # Generate RSA 4096-bit key
  %(prog)s --list                           # List existing keys
  %(prog)s --info ~/.ssh/id_ed25519         # Show key information

Requirements:
  - OpenSSH installed (comes with Linux/macOS/Git for Windows)
  - Or install paramiko: pip install paramiko
        """
    )

    parser.add_argument(
        "-t", "--type",
        choices=["rsa", "ed25519", "ecdsa"],
        default="ed25519",
        help="Key type (default: ed25519 - RECOMMENDED)"
    )

    parser.add_argument(
        "-b", "--bits",
        type=int,
        help="Key size in bits (for RSA/ECDSA only)"
    )

    parser.add_argument(
        "-f", "--filename",
        help="Output filename (without extension)"
    )

    parser.add_argument(
        "-p", "--passphrase",
        help="Passphrase to encrypt private key"
    )

    parser.add_argument(
        "-c", "--comment",
        help="Comment to add to the key"
    )

    parser.add_argument(
        "-e", "--email",
        help="Email address (added to comment)"
    )

    parser.add_argument(
        "-d", "--directory",
        type=Path,
        default=DEFAULT_KEY_DIR,
        help=f"Output directory (default: {DEFAULT_KEY_DIR})"
    )

    parser.add_argument(
        "--list",
        action="store_true",
        help="List existing SSH keys"
    )

    parser.add_argument(
        "--info",
        metavar="KEY_PATH",
        help="Show information about a key"
    )

    parser.add_argument(
        "-q", "--quiet",
        action="store_true",
        help="Suppress informational output"
    )

    args = parser.parse_args()

    print_banner()

    # List existing keys
    if args.list:
        print("[*] Existing SSH keys:")
        print()

        keys = list_ssh_keys(args.directory)

        if not keys:
            print("  No SSH keys found in ~/.ssh/")
        else:
            for key in keys:
                info = get_key_info(key)
                key_type = info.get('type', 'Unknown')
                bits = info.get('bits', '?')
                print(f"  - {key}")
                print(f"    Type: {key_type}, Bits: {bits}")
                print()

        return 0

    # Show key info
    if args.info:
        info = get_key_info(args.info)
        print(f"[*] Key information for: {args.info}")
        print()

        if "error" in info:
            print(f"  Error: {info['error']}")
        else:
            for key, value in info.items():
                print(f"  {key}: {value}")

        return 0

    # Generate key
    if not args.filename:
        key_type = args.type
        args.filename = f"id_{key_type}"

    key_path = args.directory / args.filename

    # Ensure .ssh directory exists
    if not ensure_ssh_directory(args.directory):
        print("[!] Failed to create SSH directory")
        return 1

    # Check if key already exists
    if key_path.exists():
        response = input(f"[!] Key '{key_path}' already exists. Overwrite? (y/N): ")
        if response.lower() != 'y':
            print("[*] Cancelled.")
            return 0

    print(f"[*] Generating {args.type.upper()} key pair...")

    # Generate key using ssh-keygen
    success, message = generate_keypair(
        key_type=args.type,
        key_path=str(key_path),
        passphrase=args.passphrase or "",
        bits=args.bits,
        comment=args.comment or "",
        email=args.email or ""
    )

    if not success:
        print(f"[!] {message}")

        # Try Python library as fallback
        print("[*] Trying paramiko fallback...")
        success, message = generate_keypair_python(
            key_type=args.type,
            key_path=str(key_path),
            passphrase=args.passphrase or "",
            bits=args.bits or 4096
        )

        if not success:
            print(f"[!] {message}")
            return 1

    print(f"[*] {message}")

    # Read and display public key
    public_key = read_public_key(str(key_path))

    if public_key:
        print_key_info(str(key_path), public_key)
    else:
        print("[!] Warning: Could not read public key")

    # Security tips
    if not args.quiet:
        print_security_tips()

    # Final instructions
    print("\n" + "=" * 60)
    print("                 NEXT STEPS")
    print("=" * 60)
    print(f"""
  1. Your private key is at: {key_path}
     - Keep this SECRET and SECURE
     - Never share it or upload to the internet

  2. Your public key is at: {key_path}.pub
     - This can be shared freely
     - Add to server's ~/.ssh/authorized_keys file

  3. To use your key:
     chmod 600 {key_path}
     ssh -i {key_path} user@server.com

  4. (Optional) Add passphrase to ssh-agent:
     ssh-add {key_path}
""")

    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\n\n[!] Interrupted by user.")
        sys.exit(130)
    except Exception as e:
        print(f"[!] Error: {e}")
        sys.exit(1)
