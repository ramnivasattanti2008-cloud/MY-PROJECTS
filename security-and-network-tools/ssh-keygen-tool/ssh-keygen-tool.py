def ensure_ssh_directory(key_dir: Path) -> bool:
    """
    Ensure the .ssh directory exists with correct permissions.

    Args:
        key_dir: Path to .ssh directory

    Returns:
        True if successful, False otherwise
    """
    try:
        key_dir.mkdir(parents=True, exist_ok=True)

        # Set correct permissions (Unix-like systems)
        if os.name != 'nt':  # Skip on Windows
            os.chmod(key_dir, 0o700)

        return True
    except Exception as e:
        print(f"[!] Error creating directory: {e}")
        return False


def check_openssh_available() -> Tuple[bool, Optional[str]]:
    """
    Check if ssh-keygen is available on the system.

    Returns:
        Tuple of (is_available, path_to_ssh_keygen)
    """
    # Try to find ssh-keygen
    paths_to_try = ["ssh-keygen"]

    # Add common Windows Git paths
    if os.name == 'nt':
        git_paths = [
            "C:\\Program Files\\Git\\usr\\bin\\ssh-keygen.exe",
            "C:\\Program Files (x86)\\Git\\usr\\bin\\ssh-keygen.exe",
        ]
        paths_to_try.extend(git_paths)

    for path in paths_to_try:
        try:
            result = subprocess.run(
                [path, "-V"],
                capture_output=True,
                text=True,
                timeout=5
            )
            # If we get here, ssh-keygen is available
            return True, path
        except FileNotFoundError:
            continue
        except Exception:
            continue

    return False, None


def get_available_keygen() -> Optional[str]:
    """
    Find an available ssh-keygen binary.

    Returns:
        Path to ssh-keygen or None
    """
    # Check if ssh-keygen is in PATH
    path = shutil.which("ssh-keygen")
    if path:
        return path

    # Check Windows Git installation
    if os.name == 'nt':
        git_paths = [
            Path("C:/Program Files/Git/usr/bin/ssh-keygen.exe"),
            Path("C:/Program Files (x86)/Git/usr/bin/ssh-keygen.exe"),
            Path(os.environ.get("ProgramFiles", "") + "/Git/usr/bin/ssh-keygen.exe"),
        ]

        for p in git_paths:
            if p.exists():
                return str(p)

    return None


