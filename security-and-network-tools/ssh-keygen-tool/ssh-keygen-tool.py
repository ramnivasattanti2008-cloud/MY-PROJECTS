# ==============================================================================
# Configuration
# ==============================================================================

# Default key directory
DEFAULT_KEY_DIR = Path.home() / ".ssh"

# Supported key types
KEY_TYPES = {
    "rsa": {
        "bits_default": 4096,
        "bits_min": 2048,
        "algorithm": "rsa",
        "description": "RSA - Most compatible, good for legacy systems"
    },
    "ed25519": {
        "bits_default": 256,
        "bits_min": 256,
        "algorithm": "ed25519",
        "description": "Ed25519 - Modern, fast, secure (RECOMMENDED)"
    },
    "ecdsa": {
        "bits_default": 521,
        "bits_min": 256,
        "algorithm": "ecdsa",
        "description": "ECDSA - Elliptic curve, good balance"
    }
}

# ==============================================================================
# Utility Functions
