def print_key_info(key_path: str, public_key: str):
    """Print formatted key information."""
    info = get_key_info(key_path)

    print("\n" + "=" * 60)
    print("                  KEY INFORMATION")
    print("=" * 60)

    if "error" not in info:
        print(f"  Type:        {info.get('type', 'Unknown')}")
        print(f"  Bits:        {info.get('bits', 'Unknown')}")
        print(f"  Fingerprint: {info.get('fingerprint', 'Unknown')}")
        print(f"  Comment:     {info.get('comment', 'None')}")
    else:
        print(f"  Info: {info['error']}")

    print(f"\n  Private Key: {key_path}")
    print(f"  Public Key:  {key_path}.pub")

    print("\n" + "-" * 60)
    print("  PUBLIC KEY (paste this into authorized_keys):")
    print("-" * 60)
    print(f"\n  {public_key}\n")


